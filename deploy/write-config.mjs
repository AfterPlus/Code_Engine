// Cloudflare Pages build step: writes frontend/config.js from environment variables.
//   CODE_ENGINE_BACKEND  URL of the Java backend (no trailing slash needed). Unset = same origin.
// Usage: node deploy/write-config.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const backend = (process.env.CODE_ENGINE_BACKEND || '').trim().replace(/\/+$/, '');
if (backend && !/^https?:\/\/[^\s/]+$/.test(backend)) {
  console.error(`CODE_ENGINE_BACKEND must be an origin like https://api.example.com, got: ${backend}`);
  process.exit(1);
}

const target = fileURLToPath(new URL('../frontend/config.js', import.meta.url));
writeFileSync(target, `// Generated by deploy/write-config.mjs.\nwindow.CODE_ENGINE_CONFIG = ${JSON.stringify({ backend })};\n`);
console.log(`Wrote ${target} (backend: ${backend || 'same origin'})`);
